import Foundation
import CryptoKit
import Darwin
import MacVMCore

public enum WindowsMachinePreparation {
    // Fresh Setup plus initial updates used about 27 GB in the acceptance VM.
    // Leave headroom for updates and host writes after the ISO is downloaded.
    public static let requiredFreeBytes = 40 * VMStorage.gib
    public static let downloadPage = URL(string: "https://www.microsoft.com/en-us/software-download/windows11arm64")!
    public static let downloadHosts = ["software.download.prss.microsoft.com", "software-download.microsoft.com", "download.microsoft.com"]

    public static func validateDownloadURL(_ url: URL) throws {
        guard url.scheme == "https", downloadHosts.contains(url.host?.lowercased() ?? ""),
              url.user == nil, url.password == nil, url.port == nil || url.port == 443,
              url.path.lowercased().hasSuffix(".iso") else {
            throw VMError.message("Paste the ARM64 ISO download link generated by Microsoft's official page.")
        }
    }

    public static func spaceProblem(location: URL) -> String? {
        VMStorage.availableBytes(at: location) < requiredFreeBytes
            ? "Windows installation needs at least 43 GB of free space at this location." : nil
    }

    public static func inspectISO(_ iso: URL, expectedSHA256: String? = nil) throws {
        let values = try iso.resourceValues(forKeys: [.isRegularFileKey, .isSymbolicLinkKey, .fileSizeKey])
        guard values.isRegularFile == true, values.isSymbolicLink != true,
              (values.fileSize ?? 0) > 1_000_000_000, iso.pathExtension.lowercased() == "iso" else {
            throw VMError.message("Choose a regular Windows 11 ARM64 ISO file.")
        }
        if let expected = expectedSHA256, !expected.isEmpty {
            guard expected.count == 64, expected.allSatisfy({ $0.isHexDigit }) else { throw VMError.message("Enter a SHA-256 containing 64 hexadecimal characters.") }
            let input = try FileHandle(forReadingFrom: iso); defer { try? input.close() }
            var hash = SHA256()
            while let data = try input.read(upToCount: 8 * 1024 * 1024), !data.isEmpty {
                try Task.checkCancellation(); hash.update(data: data)
            }
            let actual = hash.finalize().map { String(format: "%02x", $0) }.joined()
            guard actual == expected.lowercased() else { throw VMError.message("The Windows ISO checksum does not match. No machine was created.") }
        }
        let mount = FileManager.default.temporaryDirectory.appendingPathComponent("macvm-iso-" + UUID().uuidString)
        try FileManager.default.createDirectory(at: mount, withIntermediateDirectories: false)
        defer { try? FileManager.default.removeItem(at: mount) }
        try execute(URL(fileURLWithPath: "/usr/bin/hdiutil"), ["attach", "-readonly", "-nobrowse", "-mountpoint", mount.path, iso.path])
        defer { try? execute(URL(fileURLWithPath: "/usr/bin/hdiutil"), ["detach", mount.path]) }
        let contents = try FileManager.default.subpathsOfDirectory(atPath: mount.path)
        guard contents.contains(where: { $0.lowercased() == "sources/boot.wim" }),
              contents.contains(where: { $0.lowercased() == "setup.exe" }),
              let boot = contents.first(where: { $0.lowercased() == "efi/boot/bootaa64.efi" }) else {
            throw VMError.message("This is not a Windows ARM64 installer. Intel/x64 ISOs cannot run here.")
        }
        let image = try FileHandle(forReadingFrom: mount.appendingPathComponent(boot)); defer { try? image.close() }
        let header = try image.read(upToCount: 64) ?? Data()
        guard header.count == 64, header[0] == 0x4d, header[1] == 0x5a else { throw VMError.message("Invalid Windows ARM64 boot image.") }
        let offset = header[60..<64].enumerated().reduce(UInt64(0)) { $0 | UInt64($1.element) << (8 * $1.offset) }
        guard offset < 16_777_216 else { throw VMError.message("Invalid Windows boot image.") }
        try image.seek(toOffset: offset)
        let pe = try image.read(upToCount: 6) ?? Data()
        guard pe == Data([0x50, 0x45, 0, 0, 0x64, 0xaa]) else { throw VMError.message("The Windows installer must use ARM64.") }
    }

    public static func prepare(record initial: VirtualMachineRecord, location: URL, iso: URL, engine: URL,
                               expectedSHA256: String? = nil) throws -> VMEntry {
        var record = initial
        record.bootFromInstaller = true; record.windowsInstallationPending = true
        record.sourceImagePath = iso.path; record.osVersion = "Windows 11 ARM"; record.audioEnabled = true
        try VMStorage.validate(record)
        guard record.system == .windows else { throw VMError.message("Choose Windows for this installation.") }
        if let problem = spaceProblem(location: location) { throw VMError.message(problem) }
        for file in ["qemu-img", "swtpm_setup", "swtpm", "edk2-arm-secure-vars.fd", "DisplayTools.iso"] {
            guard FileManager.default.fileExists(atPath: engine.appendingPathComponent(file).path) else {
                throw VMError.message("Windows support is missing from this MacVM build. Reinstall MacVM.")
            }
        }
        try inspectISO(iso, expectedSHA256: expectedSHA256)
        try Task.checkCancellation()
        let staging = location.appendingPathComponent(".\(record.id.uuidString).creating")
        try FileManager.default.createDirectory(at: staging, withIntermediateDirectories: false, attributes: [.posixPermissions: 0o700])
        do {
            let copy = staging.appendingPathComponent("Installer.iso")
            if clonefile(iso.path, copy.path, 0) != 0 {
                let size = UInt64((try iso.resourceValues(forKeys: [.fileSizeKey])).fileSize ?? 0)
                guard VMStorage.availableBytes(at: location) >= requiredFreeBytes + size else { throw VMError.message("This volume needs room for the Windows ISO copy and 43 GB for installation.") }
                try FileManager.default.copyItem(at: iso, to: copy)
            }
            try execute(engine.appendingPathComponent("qemu-img"), ["create", "-f", "qcow2", staging.appendingPathComponent("Disk.qcow2").path, "\(record.diskGB)G"])
            try FileManager.default.copyItem(at: engine.appendingPathComponent("edk2-arm-secure-vars.fd"), to: staging.appendingPathComponent("EFI.fd"))
            let tpm = staging.appendingPathComponent("TPM")
            try FileManager.default.createDirectory(at: tpm, withIntermediateDirectories: false, attributes: [.posixPermissions: 0o700])
            try execute(engine.appendingPathComponent("swtpm_setup"), ["--tpm2", "--tpmstate", tpm.path,
                        "--tpm", "./swtpm socket", "--config", engine.appendingPathComponent("swtpm_setup.conf").path,
                        "--createek", "--pcr-banks", "sha256"], directory: engine)
            for name in ["Installer.iso", "Disk.qcow2", "EFI.fd"] {
                try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: staging.appendingPathComponent(name).path)
            }
            try record.save(to: staging)
            try Task.checkCancellation()
            let published = location.appendingPathComponent(record.id.uuidString).appendingPathExtension("macvm")
            try FileManager.default.moveItem(at: staging, to: published)
            do { _ = try VMStorage.validateBundle(at: published) }
            catch { try? FileManager.default.moveItem(at: published, to: staging); throw error }
            return VMEntry(record: record, url: published)
        } catch { try? FileManager.default.removeItem(at: staging); throw error }
    }

    private static func execute(_ executable: URL, _ arguments: [String], directory: URL? = nil) throws {
        try Task.checkCancellation()
        let process = Process(); process.executableURL = executable; process.arguments = arguments
        process.currentDirectoryURL = directory
        process.environment = ["PATH": "/usr/bin:/bin", "HOME": FileManager.default.homeDirectoryForCurrentUser.path]
        let output = FileManager.default.temporaryDirectory.appendingPathComponent("macvm-preparation-" + UUID().uuidString)
        FileManager.default.createFile(atPath: output.path, contents: nil, attributes: [.posixPermissions: 0o600])
        let log = try FileHandle(forWritingTo: output); defer { try? log.close(); try? FileManager.default.removeItem(at: output) }
        process.standardOutput = log; process.standardError = log
        try process.run()
        let deadline = Date().addingTimeInterval(120)
        while process.isRunning {
            if Task.isCancelled || Date() > deadline { process.terminate(); process.waitUntilExit(); try Task.checkCancellation(); throw VMError.message("Windows preparation timed out.") }
            Thread.sleep(forTimeInterval: 0.05)
        }
        guard process.terminationStatus == 0 else {
            let message = (try? String(contentsOf: output, encoding: .utf8)) ?? ""
            throw VMError.message("Windows preparation failed: " + String(message.suffix(1500)))
        }
    }
}
